const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'flick-test-'));
process.env.FLICK_DATA_DIR = dir;
const { app, db, cleanup } = require('../server');
const server = app.listen(0, '127.0.0.1');
after(() => { server.close(); db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
test('pair, transfer arbitrary files intact, restrict access and remove expired files', async () => {
  if (!server.listening) await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const json = (url, data) => fetch(base+url, { method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify(data) });
  const created = await json('/api/sessions', {origin:base});
  const cookie = created.headers.get('set-cookie').split(';')[0];
  const session = await created.json();
  assert.equal(session.code.length, 8);
  assert.equal((await json('/api/join',{code:'bad'})).status, 400);
  const sender = await (await json('/api/join',{code:session.code})).json();
  const auth = token => ({Authorization:`Bearer ${token}`});
  const bytes = Buffer.from('a real file, unchanged');
  const form = new FormData(); form.append('file', new Blob([bytes]), 'notes.txt');
  const uploaded = await fetch(`${base}/api/sessions/${session.id}/files`,{method:'POST',headers:auth(sender.sender),body:form});
  assert.equal(uploaded.status, 200);
  const file = await uploaded.json();
  const fileUrl = `${base}/api/sessions/${session.id}/files/${file.id}`;
  assert.equal((await fetch(fileUrl)).status, 404);
  const download = await fetch(fileUrl,{headers:{Cookie:cookie}});
  assert.equal(download.status, 200);
  assert.match(download.headers.get('content-disposition'), /attachment/);
  assert.deepEqual(Buffer.from(await download.arrayBuffer()), bytes);
  const status = await (await fetch(`${base}/api/sessions/${session.id}`,{headers:auth(session.receiver)})).json();
  assert.equal(status.file.name, 'notes.txt');
  assert.equal((await (await fetch(`${base}/api/history`)).json()).files.length, 0);
  const history = await (await fetch(`${base}/api/history`, {headers:{Cookie:cookie}})).json();
  assert.equal(history.files.length, 1);
  assert.equal(history.files[0].name, 'notes.txt');
  db.prepare('UPDATE files SET expires = ? WHERE id = ?').run(Date.now()-1,file.id);
  assert.equal((await (await fetch(`${base}/api/history`, {headers:{Cookie:cookie}})).json()).files.length, 0);
  assert.equal((await fetch(fileUrl,{headers:{Cookie:cookie}})).status, 404);
  cleanup();
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM files').get().n, 0);
  assert.equal(fs.existsSync(path.join(dir,'files',file.id)), false);
});
test('resumable uploads recover offsets, keep files separate, preview PDFs and delete early', async () => {
  if (!server.listening) await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const json = (url, data, headers = {}) => fetch(base + url, { method:'POST', headers:{ 'Content-Type':'application/json', ...headers }, body:JSON.stringify(data) });
  const created = await json('/api/sessions', {origin:base});
  const cookie = created.headers.get('set-cookie').split(';')[0];
  const session = await created.json();
  const sender = await (await json('/api/join', {code:session.code})).json();
  const headers = { Authorization:`Bearer ${sender.sender}` };
  const prefix = `/api/sessions/${session.id}`;
  const bytes = Buffer.from('%PDF-1.4 example content');
  const fingerprint = require('node:crypto').createHash('sha256').update(bytes).digest('hex');
  const details = {name:'document.pdf',size:bytes.length,fingerprint};
  const upload = await (await json(prefix + '/uploads', details, headers)).json();
  const put = (id, offset, body) => fetch(`${base}${prefix}/uploads/${id}`,{method:'PUT',headers:{...headers,'Content-Type':'application/octet-stream','Upload-Offset':String(offset)},body});
  assert.equal((await put(upload.id, 0, bytes.subarray(0, 6))).status, 200);
  assert.equal((await put(upload.id, 0, bytes.subarray(0, 6))).status, 409);
  const resumed = await (await json(prefix + '/uploads', details, headers)).json();
  assert.equal(resumed.offset, 6);
  const complete = await (await put(upload.id, resumed.offset, bytes.subarray(6))).json();
  assert.equal(complete.complete, true);
  assert.equal((await (await json(prefix + '/uploads', details, headers)).json()).complete, true);
  assert.equal((await (await put(upload.id, resumed.offset, bytes.subarray(6))).json()).complete, true);
  const second = await (await json(prefix + '/uploads', {...details, name:'second.pdf'}, headers)).json();
  await put(second.id, 0, bytes);
  const state = await (await fetch(base + prefix,{headers:{Authorization:`Bearer ${session.receiver}`}})).json();
  assert.equal(state.files.length, 2);
  const url = `${base}${prefix}/files/${upload.id}`;
  const preview = await fetch(url + '?preview=1', {headers:{Cookie:cookie}});
  assert.match(preview.headers.get('content-type'), /^application\/pdf/);
  assert.equal((await fetch(url,{method:'DELETE',headers:{'X-Flick-Request':'1'}})).status, 404);
  assert.equal((await fetch(url,{method:'DELETE',headers:{Cookie:cookie,'X-Flick-Request':'1'}})).status, 200);
  assert.equal((await fetch(url,{headers:{Cookie:cookie}})).status, 404);
  assert.equal((await (await fetch(base + '/api/history',{headers:{Cookie:cookie}})).json()).files.length, 1);
  const emptyHash = require('node:crypto').createHash('sha256').digest('hex');
  const empty = await (await json(prefix + '/uploads', {name:'empty.txt', size:0, fingerprint:emptyHash}, headers)).json();
  assert.equal((await (await put(empty.id, 0, Buffer.alloc(0))).json()).complete, true);
  const videoBytes = Buffer.concat([Buffer.from([0, 0, 0, 16]), Buffer.from('ftypisom'), Buffer.alloc(8)]);
  const videoHash = require('node:crypto').createHash('sha256').update(videoBytes).digest('hex');
  const video = await (await json(prefix + '/uploads', {name:'clip.mp4', size:videoBytes.length, fingerprint:videoHash}, headers)).json();
  await put(video.id, 0, videoBytes);
  const videoPreview = await fetch(`${base}${prefix}/files/${video.id}?preview=1`, {headers:{Cookie:cookie, Range:'bytes=0-3'}});
  assert.equal(videoPreview.status, 206);
  assert.match(videoPreview.headers.get('content-type'), /^video\/mp4/);
  const unfinished = await (await json(prefix + '/uploads', {...details, name:'unfinished.pdf'}, headers)).json();
  await put(unfinished.id, 0, bytes.subarray(0, 6));
  db.prepare('UPDATE uploads SET expires = ? WHERE id = ?').run(Date.now() - 1, unfinished.id);
  cleanup();
  assert.equal(fs.existsSync(path.join(dir, 'files', unfinished.id)), false);
  assert.equal(fs.existsSync(path.join(dir, 'files', video.id)), true);
});
